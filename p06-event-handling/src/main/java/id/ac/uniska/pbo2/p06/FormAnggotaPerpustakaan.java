// Validasi ketika pengguna meninggalkan input
private void pasangValidasiFocus() {

    npmText.addFocusListener(new FocusAdapter() {
        @Override
        public void focusLost(FocusEvent evt) {
            if (!npmText.getText().isBlank()) {
                periksaNpm();
            }
        }
    });

    namaText.addFocusListener(new FocusAdapter() {
        @Override
        public void focusLost(FocusEvent evt) {
            if (!namaText.getText().isBlank()) {
                periksaNama();
            }
        }
    });

    emailText.addFocusListener(new FocusAdapter() {
        @Override
        public void focusLost(FocusEvent evt) {
            if (!emailText.getText().isBlank()) {
                periksaEmail();
            }
        }
    });

    nomorHpField.addFocusListener(new FocusAdapter() {
        @Override
        public void focusLost(FocusEvent evt) {
            if (!nomorHpField.getText().isBlank()) {
                periksaHp();
            }
        }
    });
}

// Validasi seluruh form saat tombol Daftar diklik
private int validasiSemua() {

    int jumlahKesalahan = 0;

    periksaNpm();
    periksaNama();
    periksaEmail();
    periksaHp();

    if (validasiNpm() != null) {
        jumlahKesalahan++;
    }

    if (validasiNama() != null) {
        jumlahKesalahan++;
    }

    if (validasiEmail() != null) {
        jumlahKesalahan++;
    }

    if (validasiHp() != null) {
        jumlahKesalahan++;
    }

    return jumlahKesalahan;
}

// Mengarahkan fokus ke kesalahan pertama
private void fokusKesalahanPertama() {

    if (validasiNpm() != null) {
        npmText.requestFocusInWindow();
    } else if (validasiNama() != null) {
        namaText.requestFocusInWindow();
    } else if (validasiEmail() != null) {
        emailText.requestFocusInWindow();
    } else if (validasiHp() != null) {
        nomorHpField.requestFocusInWindow();
    }
}

