    private void batalButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_batalButtonActionPerformed
  boolean adaData =
            !npmText.getText().isBlank()
            || !namaText.getText().isBlank()
            || !emailText.getText().isBlank()
            || !nomorHpField.getText().isBlank()
            || !alamatArea.getText().isBlank()
            || jenisAnggotaButtonGroup.getSelection() != null
            || persetujuanCheck.isSelected();

    if (adaData) {

        int pilihan = JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin mengosongkan seluruh form?",
                "Konfirmasi Batal",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        if (pilihan != JOptionPane.YES_OPTION) {
            return;
        }
    }

    // Kosongkan seluruh input
    npmText.setText("");
    namaText.setText("");
    programStudiCombo.setSelectedIndex(0);

    jenisAnggotaButtonGroup.clearSelection();

    emailText.setText("");
    nomorHpField.setText("");
    alamatArea.setText("");

    persetujuanCheck.setSelected(false);

    // Reset pesan kesalahan
    npmPesanLabel.setText(" ");
    namaPesanLabel.setText(" ");
    emailPesanLabel.setText(" ");
    nomorHpPesanLabel.setText(" ");

    // Kembalikan border
    npmText.setBorder(borderNpm);
    namaText.setBorder(borderNama);
    emailText.setBorder(borderEmail);
    nomorHpField.setBorder(borderHp);

    npmText.setToolTipText(
            "Masukkan NPM sebanyak 10 digit angka"
    );
    namaText.setToolTipText(
            "Masukkan nama lengkap tanpa angka"
    );
    emailText.setToolTipText(
            "Masukkan email dengan format yang benar"
    );
    nomorHpField.setToolTipText(
            "Masukkan nomor HP yang diawali 08"
    );

    npmInfoLabel.setText("0 dari 10 digit");

    daftarButton.setEnabled(false);

    npmText.requestFocusInWindow();
    }//GEN-LAST:event_batalButtonActionPerformed

    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
int jumlahKesalahan = validasiSemua();

    if (jumlahKesalahan > 0) {

        JOptionPane.showMessageDialog(
                this,
                "Ditemukan " + jumlahKesalahan
                + " kesalahan pada formulir.\n"
                + "Silakan perbaiki isian yang ditandai merah.",
                "Validasi Formulir",
                JOptionPane.WARNING_MESSAGE
        );

        fokusKesalahanPertama();
        return;
    }

    if (!persetujuanCheck.isSelected()) {
        JOptionPane.showMessageDialog(
                this,
                "Anda harus menyetujui tata tertib perpustakaan.",
                "Persetujuan",
                JOptionPane.WARNING_MESSAGE
        );

        persetujuanCheck.requestFocusInWindow();
        return;
    }

    String jenisAnggota = "";

    if (umumRadio.isSelected()) {
        jenisAnggota = "Umum";
    } else if (mahasiswaRadio.isSelected()) {
        jenisAnggota = "Mahasiswa";
    } else if (dosenRadio.isSelected()) {
        jenisAnggota = "Dosen";
    }

    String ringkasan =
            "RINGKASAN PENDAFTARAN ANGGOTA\n\n"
            + "NPM: " + npmText.getText() + "\n"
            + "Nama: " + namaText.getText() + "\n"
            + "Program Studi: "
            + programStudiCombo.getSelectedItem() + "\n"
            + "Jenis Anggota: " + jenisAnggota + "\n"
            + "Email: " + emailText.getText() + "\n"
            + "Nomor HP: " + nomorHpField.getText() + "\n"
            + "Alamat: " + alamatArea.getText();

    JOptionPane.showMessageDialog(
            this,
            ringkasan,
            "Data Anggota Perpustakaan",
            JOptionPane.INFORMATION_MESSAGE
    );
    }//GEN-LAST:event_daftarButtonActionPerformed

